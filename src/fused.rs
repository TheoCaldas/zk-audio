//! Fused composition of pointwise edits: one proof for the whole
//! composite relation.
//!
//! ```text
//!   orig --[f1 . f2 . f3]--> edited
//!              pi
//! ```
//!
//! Where [`crate::chain`] proves one stage per proof and links them by
//! commitment equality, this proves `edit = f3(f2(f1(orig)))` in a single
//! step circuit: the input is decompressed once, every stage's relation is
//! applied digit-wise in signals, and the result is recompressed once. Only
//! the input and the final output are committed to.
//!
//! The intermediate streams therefore get no commitment and cannot be
//! referred to later; that is the trade for the saving. Only pointwise
//! stages can fuse, so crop/concat/merge stay in a sequential chain.
//!
//! The circuits are generated by `scripts/gen_fused_circuit.py`. See
//! docs/edit_chains.md, "Fusion".

use ff::PrimeField;
use p256::ecdsa::{Signature, SigningKey, VerifyingKey};

use crate::audio_parser;
use crate::bench::config::{comp_size_for, find_edit, EditCtx, EditSpec};
use crate::chain::{ChainConfig, ChainError, Stage};
use crate::circuit::{self, CaseMeta, ProofMetrics, RunConfig};
use crate::poseidon::BatchHashKind;
use crate::protocol::{self, VerifyError};
use crate::signer;

/// Edits with a sample-level relation that can be composed in registers.
///
/// Excludes the length- and arity-changing edits, which have no `f(x)` to
/// fuse, and `gain2`, whose legacy arity-2-chain hashing the fused
/// circuits do not reproduce. Mirrors `STAGES` in
/// `scripts/gen_fused_circuit.py`; the generator rejects anything else, so
/// the two lists disagreeing shows up as a missing artefact rather than a
/// wrong proof.
pub const FUSABLE: &[&str] = &[
    "gain_k2",
    "gain_k3",
    "gain_k4",
    "atten_m1",
    "atten_m2",
    "dist_d100",
    "dist_d50",
    "tremolo_f5",
];

/// LFO period used only to rebuild the edited pad. Any non-zero value
/// gives the same pad, because every fusable edit maps silence to a
/// phase-independent value; the reference rejects zero.
const PAD_PERIOD: usize = 8820;

pub fn is_fusable(edit: &str) -> bool {
    FUSABLE.contains(&edit)
}

/// Compiled-artifact stem for a fused chain, matching `fused_stem` in
/// `scripts/gen_fused_circuit.py`.
pub fn fused_circuit_name_for(edits: &[String], bit_depth: usize, batch_size: usize) -> String {
    format!("fused_{}_b{}_B{}", edits.join("_"), bit_depth, batch_size)
}

/// What one fused proof established.
///
/// Carries the same fields a chain's first and last stage would, minus
/// everything about the intermediates: there is one proof, so there are no
/// links to check.
pub struct FusedProvenance {
    /// The stages this proof fused, in application order.
    pub edits: Vec<String>,
    pub circuit_name: String,
    /// Commitment to the input stream, from the proof's terminal IVC
    /// state. This is what is signed.
    pub h_orig: String,
    /// Commitment to the published output stream.
    pub h_edit: String,
    /// The proven sample counter, when a stage is time-varying.
    pub counter: Option<String>,
    pub n_samples: usize,
    /// ECDSA-P256 over `SHA256(commitment_statement(h_orig, n_samples))`.
    pub signature: Signature,
    pub metrics: ProofMetrics,
}

impl FusedProvenance {
    /// Prove-side wall time, in milliseconds. Comparable with
    /// [`crate::chain::ChainProvenance::total_prove_ms`], which sums the
    /// same four phases over its stages.
    pub fn total_prove_ms(&self) -> f64 {
        self.metrics.public_params_ms
            + self.metrics.recursive_prove_ms
            + self.metrics.compressed_setup_ms
            + self.metrics.compressed_prove_ms
    }

    pub fn total_recursive_prove_ms(&self) -> f64 {
        self.metrics.recursive_prove_ms
    }

    /// The compression toll, paid once rather than once per stage.
    pub fn total_compressed_prove_ms(&self) -> f64 {
        self.metrics.compressed_setup_ms + self.metrics.compressed_prove_ms
    }

    pub fn total_constraints(&self) -> usize {
        self.metrics.constraints_primary
    }
}

/// Why a fused chain could not be built or proven.
#[derive(Debug)]
pub enum FusedError {
    Empty,
    UnknownEdit(String),
    /// The edit has no sample-level relation to fuse.
    NotFusable { edit: String },
    UnsupportedBitDepth {
        edit: String,
        bit_depth: usize,
        available: Vec<usize>,
    },
    /// No compiled artefact for this combination. Fused circuits are one
    /// artefact per chain spec, so a new chain order needs a new compile.
    MissingArtifact { circuit_name: String, hint: String },
    /// The Rust-recomputed input commitment disagrees with the proof.
    CommitmentMismatch { expected: String, recomputed: String },
    Prove(String),
    Verify(VerifyError),
}

impl std::fmt::Display for FusedError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Empty => write!(f, "a fused chain needs at least one stage"),
            Self::UnknownEdit(e) => write!(f, "unknown edit '{e}'"),
            Self::NotFusable { edit } => write!(
                f,
                "edit '{edit}' has no sample-level relation to fuse; it changes the \
                 stream length or takes two inputs, so it must stay a sequential \
                 chain stage"
            ),
            Self::UnsupportedBitDepth { edit, bit_depth, available } => write!(
                f,
                "edit '{edit}' has no relation at bit depth {bit_depth}; available: {available:?}"
            ),
            Self::MissingArtifact { circuit_name, hint } => write!(
                f,
                "no compiled artefact '{circuit_name}'. Generate and compile it:\n  {hint}"
            ),
            Self::CommitmentMismatch { expected, recomputed } => write!(
                f,
                "proof terminal state is {expected}, recomputing from the stream gives \
                 {recomputed}"
            ),
            Self::Prove(e) => write!(f, "proving failed: {e}"),
            Self::Verify(e) => write!(f, "{e}"),
        }
    }
}

impl std::error::Error for FusedError {}

/// Validates a fused stage list and resolves the artefact paths.
///
/// Separate from [`prove_fused`] so a caller can be told to compile a
/// circuit before paying for anything.
pub fn validate(
    edits: &[String],
    cfg: &ChainConfig,
) -> Result<(Vec<EditSpec>, String), FusedError> {
    if edits.is_empty() {
        return Err(FusedError::Empty);
    }

    let mut specs = Vec::with_capacity(edits.len());
    for name in edits {
        if !is_fusable(name) {
            // Distinguish "not in the registry" from "in it but not
            // pointwise": the second is a design limit, not a typo.
            if find_edit(name).is_none() {
                return Err(FusedError::UnknownEdit(name.clone()));
            }
            return Err(FusedError::NotFusable { edit: name.clone() });
        }

        let spec = find_edit(name).ok_or_else(|| FusedError::UnknownEdit(name.clone()))?;
        if !spec.bit_depths.contains(&cfg.bit_depth) {
            return Err(FusedError::UnsupportedBitDepth {
                edit: name.clone(),
                bit_depth: cfg.bit_depth,
                available: spec.bit_depths.to_vec(),
            });
        }
        specs.push(spec);
    }

    let circuit_name = fused_circuit_name_for(edits, cfg.bit_depth, cfg.batch_size);
    let r1cs = format!("artifacts/{circuit_name}.r1cs");
    if !std::path::Path::new(&r1cs).exists() {
        let stages = edits.join(" ");
        return Err(FusedError::MissingArtifact {
            circuit_name: circuit_name.clone(),
            hint: format!(
                "python3 scripts/gen_fused_circuit.py {stages} --bd {} --B {} && \
                 ./compile.circuit.sh circuits/edits/_fused/{circuit_name}.circom",
                cfg.bit_depth, cfg.batch_size
            ),
        });
    }

    Ok((specs, circuit_name))
}

/// Applies the stages in sequence, off-circuit.
///
/// Sequential, never algebraically fused: every stage floors, and
/// `floor(f2(floor(f1(x))))` is not `floor(f2(f1(x)))`. The circuit
/// composes the per-stage templates for the same reason, so this is what
/// mirrors it.
pub fn apply_stages(original: &[i32], specs: &[EditSpec], ctx: &EditCtx) -> Vec<i32> {
    let mut current = original.to_vec();
    for spec in specs {
        current = (spec.apply)(&current, ctx);
    }
    current
}

/// The prover's half: apply the composite edit, prove it in one fold
/// chain, sign the input commitment.
///
/// `original` is the unpadded input stream. The proof runs on the stream
/// padded to a fold boundary, because the relation has to hold on the pad
/// too.
///
/// Instantiate `F` at the circuit's proving field:
/// `<PallasEngine as Engine>::Scalar`.
pub fn prove_fused<F: PrimeField>(
    original: &[i32],
    edits: &[String],
    cfg: &ChainConfig,
    key: &SigningKey,
) -> Result<FusedProvenance, FusedError> {
    let (specs, circuit_name) = validate(edits, cfg)?;

    let comp_size = comp_size_for(cfg.bit_depth);
    let samples_per_step = cfg.batch_size * comp_size;

    let n_samples = original.len();
    let padded = audio_parser::pad_to_step(original, samples_per_step);

    let ctx = EditCtx {
        bit_depth: cfg.bit_depth,
        batch_size: cfg.batch_size,
        start_index: 0,
        comp_size,
        period: cfg.period,
    };

    let edited = apply_stages(&padded, &specs, &ctx);

    let json_path = format!(
        "{}/_fused_{}_{}_N{}.json",
        cfg.serialized_dir,
        cfg.tag,
        circuit_name,
        padded.len()
    );
    audio_parser::serialize_samples_at(
        &padded,
        &edited,
        samples_per_step,
        cfg.bit_depth as u32,
        &json_path,
    );

    // A fused chain's state is 3-wide exactly when one of its stages is
    // time-varying, because the LFO phase is a function of the proven
    // sample counter.
    let state_width = if specs.iter().any(|s| s.state_width == 3 && !s.multi_input) {
        3
    } else {
        2
    };

    let r1cs = format!("artifacts/{circuit_name}.r1cs");
    let wasm = format!("artifacts/{circuit_name}_js/{circuit_name}.wasm");

    let run_cfg = RunConfig {
        circuit_filepath: &r1cs,
        witness_gen_filepath: &wasm,
        json_input_filepath: &json_path,
        skip_compressed: cfg.skip_compressed,
        verbose: false,
        progress: cfg.progress,
        multi_input: false,
        initial_state: Vec::new(),
        state_width,
    };
    let meta = CaseMeta {
        circuit_name: circuit_name.clone(),
        edit: edits.join("+"),
        audio_input: cfg.audio_input.clone(),
        bit_depth: cfg.bit_depth,
        batch_size: cfg.batch_size,
        comp_size,
        total_samples: padded.len(),
        repetition: 0,
    };

    let metrics =
        circuit::run_proof(&run_cfg, &meta).map_err(|e| FusedError::Prove(e.to_string()))?;

    let hash_kind = BatchHashKind::for_circuit(&circuit_name);
    let h_orig = audio_parser::hex_stream_commitment::<F>(
        &padded,
        cfg.bit_depth as u32,
        samples_per_step,
        hash_kind,
    );
    if h_orig != metrics.final_hash_original {
        return Err(FusedError::CommitmentMismatch {
            expected: metrics.final_hash_original.clone(),
            recomputed: h_orig,
        });
    }

    let _ = std::fs::remove_file(&json_path);

    let signature = signer::sign_hash(&protocol::signed_digest(&h_orig, n_samples), key);

    Ok(FusedProvenance {
        edits: edits.to_vec(),
        circuit_name,
        h_orig,
        h_edit: metrics.final_hash_edited.clone(),
        counter: metrics.final_counter.clone(),
        n_samples,
        signature,
        metrics,
    })
}

/// The verifier's half: recompute the published stream's commitment and
/// check the signature over the input.
///
/// One proof, so there are no links; what remains is binding the published
/// audio and the signed input to the single proof. The proof itself is
/// verified inside `run_proof` at proving time, as it is for a chain.
///
/// `edited` is the unpadded published stream.
pub fn verify_fused<F: PrimeField>(
    edited: &[i32],
    bit_depth: u32,
    samples_per_step: usize,
    prov: &FusedProvenance,
    pubkey: &VerifyingKey,
) -> Result<(), FusedError> {
    // Every fusable stage is length-preserving, so the published stream
    // has as many samples as the signed input.
    if edited.len() != prov.n_samples {
        return Err(FusedError::Verify(VerifyError::LengthMismatch {
            signed: prov.n_samples,
            published: edited.len(),
        }));
    }

    // The proof folds over the stream padded to a fold boundary, so a
    // published stream trimmed to `n_samples` has to have that pad
    // restored before its commitment can match. The pad is the composite
    // edit applied to silence, not silence: `dist_d100` maps 0 to -128,
    // so a zero-filled pad commits to a different stream. Every fusable
    // edit's value on silence is index-independent - tremolo scales zero
    // to zero at any LFO phase, and the rest are memoryless - so the pad
    // needs no phase and the period the prover used does not have to be
    // recovered. It must still be non-zero: the tremolo reference
    // rejects a zero period.
    let specs: Vec<EditSpec> = prov
        .edits
        .iter()
        .map(|e| find_edit(e).ok_or_else(|| FusedError::UnknownEdit(e.clone())))
        .collect::<Result<_, _>>()?;
    let ctx = EditCtx {
        bit_depth: bit_depth as usize,
        batch_size: samples_per_step / comp_size_for(bit_depth as usize),
        start_index: 0,
        comp_size: comp_size_for(bit_depth as usize),
        period: PAD_PERIOD,
    };
    let padded = audio_parser::pad_edited_to_step(edited, samples_per_step, |_from, len| {
        apply_stages(&vec![0i32; len], &specs, &ctx)
    });

    let hash_kind = BatchHashKind::for_circuit(&prov.circuit_name);
    let recomputed =
        audio_parser::hex_stream_commitment::<F>(&padded, bit_depth, samples_per_step, hash_kind);
    if recomputed != prov.h_edit {
        return Err(FusedError::Verify(VerifyError::EditedCommitmentMismatch {
            expected: prov.h_edit.clone(),
            recomputed,
        }));
    }

    if !signer::verify_hash(
        &protocol::signed_digest(&prov.h_orig, prov.n_samples),
        &prov.signature,
        pubkey,
    ) {
        return Err(FusedError::Verify(VerifyError::BadSignature));
    }

    Ok(())
}

/// Maps a [`crate::chain::Stage`] list onto the fused edit names, for a
/// caller holding a chain spec it wants to prove both ways.
///
/// Rejects a two-input stage: `Stage::stream_b` has nowhere to go in a
/// unary composite.
pub fn edits_from_stages(stages: &[Stage]) -> Result<Vec<String>, ChainError> {
    for s in stages {
        if s.stream_b.is_some() {
            return Err(ChainError::StreamBMismatch {
                edit: s.edit.clone(),
                expected: false,
            });
        }
    }
    Ok(stages.iter().map(|s| s.edit.clone()).collect())
}
