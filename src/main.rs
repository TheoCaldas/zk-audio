//! Single-run demo of the FULL protocol, end to end:
//!
//!     hash -> sign -> prove -> verify proof -> recompute hash -> verify sig
//!
//! On success it writes the edited stream to raw_audios/output/, which is
//! the artefact a creator would publish alongside (h_orig, sigma, pi).
//!
//! Previously this driver stopped after proving, because the Rust-side
//! Poseidon ran over BN254 while the circuits prove over Vesta, so a
//! recomputed commitment could never be compared against the proof's
//! terminal IVC state. With `zk_audio::poseidon` the two agree, which is
//! what lets steps 5-6 exist at all. See
//! README.md, "Poseidon parity" and "How it works".
//!
//! For sweeps across B and N, use the benchmark suite:
//!     cargo run --release --bin bench -- --max-n 6000

use nova_snark::traits::Engine;

use zk_audio::{
    audio_parser,
    bench::config::{circuit_name_for, comp_size_for, find_edit, EditCtx},
    circuit::{CaseMeta, RunConfig},
    poseidon::BatchHashKind,
    protocol, signer,
};

/// The field the circuits prove in: the scalar field of Nova's primary
/// curve, which is what `--prime vesta` compiles against.
type Fq = <nova_snark::provider::PallasEngine as Engine>::Scalar;

fn main() {
    /* Inputs */
    let bit_depth = 16;
    let batch_size = 100;
    let max_size = 600000;
    // `gain_k2` is the PRODUCTION relation: clamp(2x), proven by
    // circuits/edits/gain/gain_step.circom, which commits to both streams
    // with the rate-4 sponge. The legacy `gain2` (circuits/_old,
    // unclamped, arity-2 chain) is kept only as the benchmark baseline.
    let edit_name = "gain_k2";
    // Generated by scripts/gen_bench_fixture.py, so a fresh clone can
    // reproduce it. NOTE this fixture is capped at 1/4 full scale, so
    // gain_k2's clamping branch is never taken on it - see the comment
    // where `edited` is applied.
    let input_name = "sweep_120s_2c_44sr_16bd";
    let key_id = "p256_260426";

    // Naming convention: b = bit depth, B = batch size, N = total samples.
    let comp_size = comp_size_for(bit_depth);
    let edit = find_edit(edit_name).expect("unknown edit");

    // One batch covers batch_size * comp_size samples; N must be a whole
    // number of batches or the circuit rejects the short final one.
    let samples_per_step = batch_size * comp_size;
    assert_eq!(
        max_size % samples_per_step,
        0,
        "N={} is not a multiple of {} samples/step (B={})",
        max_size,
        samples_per_step,
        batch_size
    );

    // Use the shared namer, not an inline format!: the gain and atten
    // families encode their factor in the stem (gain_b16_k3_B100,
    // atten_b8_m1_B100), so a hand-rolled "{prefix}_b{bd}_B{B}" only ever
    // resolves for the gain2 baseline.
    let circuit_name = &circuit_name_for(edit.circuit_prefix, edit.factor, bit_depth, batch_size);
    let circuit_filepath = &format!("artifacts/{}.r1cs", circuit_name);
    // Which batch-digest construction this circuit uses. The current step
    // circuits absorb with a rate-4 sponge; the legacy `multiplier_*`
    // (gain2) family still uses the arity-2 BatchHasher chain, and the two
    // digests differ, so the commitment has to follow the circuit rather
    // than assume the current default.
    let hash_kind = BatchHashKind::for_circuit(circuit_name);
    let witness_gen_filepath = &format!("artifacts/{}_js/{}.wasm", circuit_name, circuit_name);

    /* Read Audio Samples */
    // Read at i32 so 24-bit samples survive; the edit registry and the
    // depth-generic serializer both take i32 now.
    let input_filepath = &format!("raw_audios/{}.wav", input_name);
    let (original, _file_bits) = audio_parser::read_samples_signed(input_filepath);
    // Needed to write the edited stream back out in the input's own format.
    let (sample_rate, channels) = audio_parser::read_rate_and_channels(input_filepath);
    assert!(
        original.len() >= max_size,
        "audio has {} samples, need {}",
        original.len(),
        max_size
    );
    let original = &original[0..max_size];

    assert!(
        edit.bit_depths.contains(&bit_depth),
        "edit '{}' has no circuit at bit depth {}; available: {:?}",
        edit_name,
        bit_depth,
        edit.bit_depths
    );

    /* Apply Edit */
    let ctx = EditCtx {
        bit_depth,
        batch_size,
        start_index: 0,
        comp_size,
        period: 8820, // 5Hz at 44.1kHz, for time-varying edits
    };
    let edited = (edit.apply)(original, &ctx);

    /* Serialize Samples */
    let json_input_filepath = &format!("serialized/{}_N{}.json", circuit_name, max_size);
    // Depth-generic serializer; byte-identical to the legacy 16-bit one at
    // bit_depth=16, and the only correct choice at 8.
    let orig_wide: Vec<i32> = original.to_vec();
    let edit_wide: Vec<i32> = edited.iter().map(|&s| s as i32).collect();
    audio_parser::serialize_samples_at(
        &orig_wide,
        &edit_wide,
        samples_per_step,
        bit_depth as u32,
        json_input_filepath,
    );

    /* Load Signing Keys */
    // The creator signs; the verifier below holds only the public half.
    let signing_key = signer::import_key(&format!("signers/private_{}.pem", key_id));
    let verifying_key = signer::import_pub_key(&format!("signers/public_{}.pem", key_id));

    let cfg = RunConfig {
        circuit_filepath,
        witness_gen_filepath,
        json_input_filepath,
        skip_compressed: false,
        verbose: true,
        multi_input: edit.multi_input,
        initial_state: Vec::new(),
        state_width: edit.state_width,
    };
    let meta = CaseMeta {
        circuit_name: circuit_name.clone(),
        edit: edit_name.to_string(),
        audio_input: input_name.to_string(),
        bit_depth,
        batch_size,
        comp_size,
        total_samples: max_size,
        repetition: 0,
    };

    /* --- CREATOR: commit, sign, prove --- */
    println!();
    println!("=== Creator: commit -> sign -> prove ===");
    let prov = protocol::create_provenance::<Fq>(
        &orig_wide,
        &edit_wide,
        bit_depth as u32,
        samples_per_step,
        hash_kind,
        &signing_key,
        &cfg,
        &meta,
    )
    .expect("creating provenance failed");

    println!("h_orig (signed)   : {}", prov.h_orig);
    println!("h_edit (from proof): {}", prov.h_edit);

    /* --- VERIFIER: recompute the edited commitment, check the signature --- */
    //
    // The verifier gets the edited audio, the proof and the bundle. It does
    // NOT get `orig_wide`: recomputing h_edit from the published audio and
    // checking the signature over the committed original is the whole of
    // what it can do, and is enough.
    println!();
    println!("=== Verifier: verify proof -> recompute hash -> verify signature ===");
    match protocol::verify_provenance::<Fq>(
        &edit_wide,
        bit_depth as u32,
        samples_per_step,
        hash_kind,
        &prov,
        &verifying_key,
    ) {
        Ok(()) => {
            println!("edited-stream commitment matches the proof's terminal state");
            println!("signature over the committed original verifies");

            // Write the edited stream only AFTER verification passes, so
            // what lands on disk is always audio whose provenance checked
            // out. This is the artefact a creator would publish alongside
            // (h_orig, sigma, pi) - the proof binds to these exact samples
            // via h_edit, so re-encoding or trimming the file invalidates
            // it.
            let output_filepath =
                &format!("raw_audios/output/{}_{}.wav", input_name, edit_name);
            audio_parser::write_file_at(
                output_filepath,
                &edit_wide,
                sample_rate,
                bit_depth as u32,
                match channels {
                    1 => audio_parser::WaveType::Mono,
                    _ => audio_parser::WaveType::Stereo,
                },
            );
            println!("wrote edited audio to {}", output_filepath);

            println!();
            println!("PROTOCOL OK: the published edit is provably {} of an original", edit_name);
            println!("signed by the key holder, and the original was never revealed.");
        }
        Err(e) => {
            println!("PROTOCOL FAILED: {}", e);
            std::process::exit(1);
        }
    }
}
