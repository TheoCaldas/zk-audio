"""Generates circuits/edits/tremolo/tremolo_table.circom.

A 256-entry unipolar sine LFO at fixed-point scale 2^16:
    L[k] = round(2^16 * (1 + sin(2*pi*k/256)) / 2)   in [0, 2^16]

Unipolar (not the reference's bipolar sine) so the multiplier is never
negative, which keeps the normalized-space formulation valid. The depth
of the tremolo is therefore full (0..1); a shallower depth would scale
and offset this table.

The SAME values must be used by the Rust reference, so this file is the
single source of truth. Rust reads them from the generated table module.
"""
import math

N = 256
SCALE = 1 << 16
vals = [round(SCALE * (1 + math.sin(2 * math.pi * k / N)) / 2) for k in range(N)]
assert min(vals) >= 0 and max(vals) <= SCALE, (min(vals), max(vals))

lines = [
    "pragma circom 2.1.6;",
    "",
    "// GENERATED by docs/gen_lfo_table.py - do not edit by hand.",
    "//",
    "// Unipolar sine LFO, %d entries over one period, fixed-point scale 2^16:" % N,
    "//     L[k] = round(2^16 * (1 + sin(2*pi*k/%d)) / 2)   in [0, 2^16]" % N,
    "//",
    "// Unipolar so the multiplier is never negative (a negative multiplier",
    "// would break the normalized-space formulation in tremolo_step.circom).",
    "// The Rust reference MUST use these exact values; src/lfo_table.rs is",
    "// generated from the same script.",
    "",
    "function LfoTable() {",
    "    var t[%d];" % N,
]
for k, v in enumerate(vals):
    lines.append("    t[%d] = %d;" % (k, v))
lines += ["    return t;", "}", ""]

out = "circuits/edits/tremolo/tremolo_table.circom"
open(out, "w").write("\n".join(lines))
print("wrote %s (%d entries, range %d..%d)" % (out, N, min(vals), max(vals)))

# Rust side, same values.
rl = [
    "//! GENERATED by docs/gen_lfo_table.py - do not edit by hand.",
    "//!",
    "//! Unipolar sine LFO table shared with",
    "//! `circuits/edits/tremolo/tremolo_table.circom`. Both sides must read",
    "//! identical values or the suite proves a relation other than the one",
    "//! it reports.",
    "",
    "/// Fixed-point scale for LFO values: they represent gains in [0,1] as",
    "/// integers in [0, 2^16].",
    "pub const LFO_SCALE: i64 = 1 << 16;",
    "",
    "/// Entries per LFO period.",
    "pub const LFO_TABLE_N: usize = %d;" % N,
    "",
    "/// L[k] = round(2^16 * (1 + sin(2*pi*k/%d)) / 2)" % N,
    "pub const LFO_TABLE: [i64; %d] = [" % N,
]
for i in range(0, N, 8):
    rl.append("    " + " ".join("%d," % v for v in vals[i:i+8]))
rl += ["];", ""]
open("src/lfo_table.rs", "w").write("\n".join(rl))
print("wrote src/lfo_table.rs")
