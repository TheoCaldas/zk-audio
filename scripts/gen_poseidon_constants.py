"""Generates src/poseidon/constants.rs from circomlib's round constants.

Why this script exists
----------------------
The Rust reference hash and the Circom circuits must produce the SAME
Poseidon digest, and the only way to guarantee that is for both to read
the same round constants. Circom reads them from
`circuits/circom/poseidon_constants.circom`; this script transcribes that
file into Rust so the two cannot drift. Same contract as
`gen_lfo_table.py`.

The constants are stored as big-endian hex STRINGS, not as integers or
limbs. That is deliberate and is the whole trick behind cross-field
parity:

    circomlib's constants are literal hex. Circom reinterprets each
    literal modulo whatever prime it was invoked with (`--prime vesta`
    here). Keeping them as hex lets the Rust side do exactly the same
    thing - decode each literal into whichever `PrimeField` it is
    instantiated at - instead of baking in BN254 limbs the way
    `light-poseidon` does.

So one table serves both fields. BN254 and Vesta differ only in which
field the strings are decoded into.

Emits every arity circomlib ships constants for (t = 3..17, i.e.
Poseidon(2)..Poseidon(16)), not just the ones in use today: the circuits
here already span arity 2 (the IVC fold and `BatchHasher`), 5
(`SpongeBatchHasher(_, 4)`), 9 (the rate-8 sponge) and 16
(`WideBatchHasher`), and covering the full range costs one generated
file. `POSEIDON_C` alone also lists t=2, but circomlib ships no S/M/P at
that width and never instantiates it, so it is skipped.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "circuits" / "circom" / "poseidon_constants.circom"
OUT = ROOT / "src" / "poseidon" / "constants.rs"

# circomlib's own table, from poseidon.circom. Indexed by t-2.
N_ROUNDS_P = [56, 57, 56, 60, 60, 63, 64, 63, 60, 66, 60, 65, 70, 60, 64, 68]
N_ROUNDS_F = 8


def parse_function(src: str, name: str) -> dict:
    """Extracts {t: [hex strings]} from one POSEIDON_* function body.

    The functions are a chain of `if (t==N) { return [...] }` blocks, so
    splitting on the guard and harvesting the hex literals from each
    branch recovers the per-arity tables in order.
    """
    start = src.index("function %s(t)" % name)
    end = src.find("\nfunction ", start + 10)
    body = src[start:end if end > 0 else len(src)]

    parts = re.split(r"if \(t==(\d+)\)", body)
    out = {}
    for i in range(1, len(parts), 2):
        t = int(parts[i])
        # Normalize to lowercase, no 0x prefix, even length: the Rust side
        # decodes with hex::decode, which rejects odd-length input.
        literals = []
        for lit in re.findall(r"0x([0-9a-fA-F]+)", parts[i + 1]):
            lit = lit.lower()
            if len(lit) % 2:
                lit = "0" + lit
            literals.append(lit)
        out[t] = literals
    return out


def main() -> int:
    src = SRC.read_text()

    C = parse_function(src, "POSEIDON_C")
    S = parse_function(src, "POSEIDON_S")
    M = parse_function(src, "POSEIDON_M")
    P = parse_function(src, "POSEIDON_P")

    # POSEIDON_C covers t=2 but S/M/P start at t=3, because Poseidon(1)
    # (t=2) is never instantiated by circomlib's PoseidonEx. Emit only the
    # arities where ALL four tables exist, so a lookup can never half-hit.
    arities = sorted(set(C) & set(S) & set(M) & set(P))
    if not arities:
        print("error: no arity has all four constant tables", file=sys.stderr)
        return 1

    # Verify every table against the lengths circomlib's permutation
    # indexes into. A silent truncation here would surface much later as
    # a wrong digest, so fail loudly now.
    for t in arities:
        n_p = N_ROUNDS_P[t - 2]
        expect = {
            "C": t * N_ROUNDS_F + n_p,
            "S": n_p * (t * 2 - 1),
            "M": t * t,
            "P": t * t,
        }
        actual = {"C": len(C[t]), "S": len(S[t]), "M": len(M[t]), "P": len(P[t])}
        if expect != actual:
            print(
                "error: t=%d constant table size mismatch: expected %s, got %s"
                % (t, expect, actual),
                file=sys.stderr,
            )
            return 1

    lines = [
        "//! GENERATED by scripts/gen_poseidon_constants.py - do not edit by hand.",
        "//!",
        "//! circomlib's Poseidon round constants, transcribed from",
        "//! `circuits/circom/poseidon_constants.circom`. Both sides must read",
        "//! identical values or the Rust reference hash and the circuit",
        "//! disagree - which is exactly the bug this module exists to prevent.",
        "//!",
        "//! Stored as big-endian hex STRINGS rather than field elements or",
        "//! limbs. circomlib's constants are literal hex that circom",
        "//! reinterprets modulo whichever prime it compiles against, so",
        "//! keeping them undecoded lets one table serve any `PrimeField`:",
        "//! BN254 and Vesta differ only in where the strings are decoded.",
        "//! See `super::poseidon` for the permutation that consumes them.",
        "",
        "/// Full rounds, split half before and half after the partial rounds.",
        "pub const N_ROUNDS_F: usize = %d;" % N_ROUNDS_F,
        "",
        "/// Partial rounds per width, indexed by `t - 2`. circomlib's table.",
        "pub const N_ROUNDS_P: [usize; %d] = [" % len(N_ROUNDS_P),
        "    " + ", ".join(str(n) for n in N_ROUNDS_P) + ",",
        "];",
        "",
        "/// Lowest state width with constants available (`Poseidon(%d)`)."
        % (arities[0] - 1),
        "pub const MIN_T: usize = %d;" % arities[0],
        "",
        "/// Highest state width with constants available (`Poseidon(%d)`)."
        % (arities[-1] - 1),
        "pub const MAX_T: usize = %d;" % arities[-1],
        "",
    ]

    def emit(symbol: str, table: dict, doc: str) -> None:
        lines.append("/// %s" % doc)
        lines.append(
            "///"
        )
        lines.append(
            "/// Indexed by `t - MIN_T`; empty slice means that width is unavailable."
        )
        lines.append(
            "pub static %s: [&[&str]; %d] = [" % (symbol, arities[-1] - arities[0] + 1)
        )
        for t in range(arities[0], arities[-1] + 1):
            vals = table.get(t)
            if not vals:
                lines.append("    // t = %d: unavailable" % t)
                lines.append("    &[],")
                continue
            lines.append("    // t = %d" % t)
            lines.append("    &[")
            for v in vals:
                lines.append('        "%s",' % v)
            lines.append("    ],")
        lines.append("];")
        lines.append("")

    emit("POSEIDON_C", C, "Round constants, added to the whole state each round (`Ark`).")
    emit("POSEIDON_S", S, "Sparse matrices used by the partial rounds (`MixS`).")
    emit("POSEIDON_M", M, "The MDS matrix, row-major, used by the full rounds (`Mix`).")
    emit("POSEIDON_P", P, "Pre-sparsified MDS matrix, row-major, for the first partial round.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")

    total = sum(len(C[t]) + len(S[t]) + len(M[t]) + len(P[t]) for t in arities)
    print(
        "wrote %s: t = %d..%d, %d constants"
        % (OUT.relative_to(ROOT), arities[0], arities[-1], total)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
