#!/usr/bin/env python3
"""Generate circuits/CIRCUIT_INDEX.md.

The rate-4 sponge became the default batch hasher for every edit, which
changes the commitment digest. Every benchmark run recorded before that
switch was produced by the arity-2 chain, so its `circuit_name` no longer
identifies the circuit that is at that path today.

This maps each `circuit_name` appearing in logs/bench/ to:
  * the file that produced it (now under circuits/edits/_baseline/), and
  * the file that carries the same name today (the sponge default),

so a reader who finds a number in an old summary.md can tell which circuit
it came from, and which current circuit it is NOT comparable to.

Usage:  python3 scripts/gen_circuit_index.py > circuits/CIRCUIT_INDEX.md
"""
import collections
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Experimental one-off variants: these were never the default for any edit,
# and several are deliberately unsound. They are listed separately.
VARIANT_PREFIXES = ("gain_nohash", "gain_onehash", "gain_sponge", "gain_wide")

# The commit that made the sponge the default. Runs recorded before it used
# the arity-2 chain.
def switch_commit():
    try:
        return subprocess.run(
            ["git", "log", "-1", "--format=%h", "--", "circuits/hasher_sponge.circom"],
            cwd=ROOT, capture_output=True, text=True, check=False
        ).stdout.strip() or "(uncommitted)"
    except Exception:
        return "(unknown)"


def collect():
    """-> {circuit_name: {runs: set, edit, bd, B, n_values: set}}"""
    info = collections.defaultdict(
        lambda: {"runs": set(), "edit": None, "bd": None, "B": None, "N": set()}
    )
    for f in glob.glob(os.path.join(ROOT, "logs", "bench", "**", "results.jsonl"),
                       recursive=True):
        rel = os.path.relpath(f, ROOT)
        run = os.path.basename(os.path.dirname(f))
        group = os.path.basename(os.path.dirname(os.path.dirname(f)))
        label = f"{group}/{run}" if group != "bench" else run
        for line in open(f):
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r.get("status") != "ok":
                continue
            c = r.get("circuit_name")
            if not c:
                continue
            e = info[c]
            e["runs"].add(label)
            e["edit"] = r.get("edit") or e["edit"]
            e["bd"] = r.get("bit_depth")
            e["B"] = r.get("batch_size")
            e["N"].add(r["total_samples"])
    return info


def find(name, baseline):
    """Locate a circuit by stem, in _baseline/ or in the live tree.

    The live tree nests one level deeper for the optimisation-study
    variants (circuits/edits/gain/_experimental/), so both depths are
    searched.
    """
    base = os.path.join(ROOT, "circuits", "edits")
    if baseline:
        hits = glob.glob(os.path.join(base, "_baseline", "*", f"{name}.circom"))
    else:
        hits = [h for h in
                glob.glob(os.path.join(base, "*", f"{name}.circom"))
                + glob.glob(os.path.join(base, "*", "*", f"{name}.circom"))
                if "_baseline" not in h]
    return os.path.relpath(hits[0], ROOT) if hits else None


def main():
    info = collect()
    out = []
    w = out.append

    w("# Circuit index: benchmark history → circuit files\n")
    w("**Generated by `scripts/gen_circuit_index.py`. Do not edit by hand.**\n")
    w("The rate-4 Poseidon sponge replaced the arity-2 chain as the default")
    w("batch hasher for every edit. ")
    w("That changes the")
    w("commitment digest, so a `circuit_name` recorded in an older run does")
    w("**not** denote the circuit sitting at that path today.\n")
    w(f"Switch introduced in commit `{switch_commit()}`.\n")
    w("- **baseline file** — produced the recorded numbers; arity-2 chain.")
    w("- **current file** — same name today; rate-4 sponge, different digest.\n")
    w("Final-state hashes are comparable **only within the same column**.\n")
    w("---\n")

    prod = {k: v for k, v in info.items() if not k.startswith(VARIANT_PREFIXES)}
    var = {k: v for k, v in info.items() if k.startswith(VARIANT_PREFIXES)}

    w("## Production circuits\n")
    w("| circuit_name | edit | bd | B | baseline file | current file | runs |")
    w("|---|---|---:|---:|---|---|---|")
    for name in sorted(prod):
        e = prod[name]
        b = find(name, True) or "—"
        c = find(name, False) or "—"
        runs = ", ".join(f"`{r}`" for r in sorted(e["runs"]))
        w(f"| `{name}` | {e['edit'] or '—'} | {e['bd']} | {e['B']} | "
          f"`{b}` | `{c}` | {runs} |")

    if var:
        w("\n## Experimental variants\n")
        w("One-off circuits from the optimisation study. Never a default for")
        w("any edit; `gain_nohash`, `gain_onehash` and `gain_sponge4/8` are")
        w("**unsound** and exist only to price the commitment — see the")
        w("banners in their source and §3.1 of the analysis.\n")
        w("| circuit_name | bd | B | file | runs |")
        w("|---|---:|---:|---|---|")
        for name in sorted(var):
            e = var[name]
            f = find(name, False) or "—"
            runs = ", ".join(f"`{r}`" for r in sorted(e["runs"]))
            w(f"| `{name}` | {e['bd']} | {e['B']} | `{f}` | {runs} |")

    w("")
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
